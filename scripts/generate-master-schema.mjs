/**
 * Assemble the ordered sovereign schema from the base file and the
 * hardening scripts. Does not connect to Postgres.
 * Usage: node scripts/generate-master-schema.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function embeddedSql(relativePath) {
  const source = readFileSync(resolve(root, relativePath), "utf8");
  const match = source.match(/const sql = `([\s\S]*?)`;\s*(?:const pool|async function)/i);
  if (!match) {
    throw new Error(`No SQL template in ${relativePath}`);
  }
  return match[1].trim();
}

const storagePolicies = `
-- Storage buckets. Service role bypasses these policies.
INSERT INTO storage.buckets (id, name, public)
VALUES ('avatars', 'avatars', true)
ON CONFLICT (id) DO UPDATE SET public = EXCLUDED.public;

INSERT INTO storage.buckets (id, name, public)
VALUES ('verification-docs', 'verification-docs', false)
ON CONFLICT (id) DO UPDATE SET public = EXCLUDED.public;

DROP POLICY IF EXISTS "avatars public read" ON storage.objects;
CREATE POLICY "avatars public read" ON storage.objects
FOR SELECT USING (bucket_id = 'avatars');

DROP POLICY IF EXISTS "avatars owner insert" ON storage.objects;
CREATE POLICY "avatars owner insert" ON storage.objects
FOR INSERT TO authenticated
WITH CHECK (
  bucket_id = 'avatars'
  AND (storage.foldername(name))[1] = auth.uid()::text
);

DROP POLICY IF EXISTS "avatars owner update" ON storage.objects;
CREATE POLICY "avatars owner update" ON storage.objects
FOR UPDATE TO authenticated
USING (
  bucket_id = 'avatars'
  AND (storage.foldername(name))[1] = auth.uid()::text
)
WITH CHECK (
  bucket_id = 'avatars'
  AND (storage.foldername(name))[1] = auth.uid()::text
);

DROP POLICY IF EXISTS "avatars owner delete" ON storage.objects;
CREATE POLICY "avatars owner delete" ON storage.objects
FOR DELETE TO authenticated
USING (
  bucket_id = 'avatars'
  AND (storage.foldername(name))[1] = auth.uid()::text
);

DROP POLICY IF EXISTS "verification docs admin read" ON storage.objects;
CREATE POLICY "verification docs admin read" ON storage.objects
FOR SELECT TO authenticated
USING (
  bucket_id = 'verification-docs'
  AND public.is_admin()
);

DROP POLICY IF EXISTS "verification docs owner insert" ON storage.objects;
CREATE POLICY "verification docs owner insert" ON storage.objects
FOR INSERT TO authenticated
WITH CHECK (
  bucket_id = 'verification-docs'
  AND (
    (storage.foldername(name))[1] = auth.uid()::text
    OR name = 'signatures/' || auth.uid()::text || '.png'
  )
);

DROP POLICY IF EXISTS "verification docs owner update" ON storage.objects;
CREATE POLICY "verification docs owner update" ON storage.objects
FOR UPDATE TO authenticated
USING (
  bucket_id = 'verification-docs'
  AND (
    (storage.foldername(name))[1] = auth.uid()::text
    OR name = 'signatures/' || auth.uid()::text || '.png'
  )
)
WITH CHECK (
  bucket_id = 'verification-docs'
  AND (
    (storage.foldername(name))[1] = auth.uid()::text
    OR name = 'signatures/' || auth.uid()::text || '.png'
  )
);

DROP POLICY IF EXISTS "verification docs owner delete" ON storage.objects;
CREATE POLICY "verification docs owner delete" ON storage.objects
FOR DELETE TO authenticated
USING (
  bucket_id = 'verification-docs'
  AND (
    (storage.foldername(name))[1] = auth.uid()::text
    OR name = 'signatures/' || auth.uid()::text || '.png'
  )
);
`;

const sections = [
  ["supabase/schema.sql", readFileSync(resolve(root, "supabase/schema.sql"), "utf8").trim()],
  ["scripts/harden-database-security.mjs", embeddedSql("scripts/harden-database-security.mjs")],
  ["scripts/upgrade-border-clearance.mjs", embeddedSql("scripts/upgrade-border-clearance.mjs")],
  ["scripts/upgrade-ats-cv-schema.mjs", embeddedSql("scripts/upgrade-ats-cv-schema.mjs")],
  ["storage policies", storagePolicies.trim()],
];

const body = sections
  .map(([name, sql]) => `-- ════════════════════════════════════════════════════════════\n-- SOURCE: ${name}\n-- ════════════════════════════════════════════════════════════\n\n${sql}`)
  .join("\n\n");

const output = `-- PALPASS sovereign master schema.\n-- Generated by scripts/generate-master-schema.mjs. Apply in order; later sections override earlier policies.\n-- This file is not executed automatically.\n\n${body}\n`;

const destination = resolve(root, "supabase/schema-sovereign-master.sql");
writeFileSync(destination, output);
console.log(`wrote ${destination} (${output.length} bytes)`);
